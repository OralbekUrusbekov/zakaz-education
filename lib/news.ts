export const NEWS_CATEGORIES = [...new Set(NEWS.map((n) => n.category))]

export const getNews = (slug: string) => NEWS.find((n) => n.slug === slug)

const clean = (s: string) => s.replace(/\s*г\.$/, '').replace(/\./g, '')

export const formatNewsDate = (iso: string) =>
  clean(new Date(iso).toLocaleDateString('ru-RU', { day: 'numeric', month: 'long', year: 'numeric' }))

export const formatNewsDateShort = (iso: string) =>
  clean(new Date(iso).toLocaleDateString('ru-RU', { day: 'numeric', month: 'short', year: 'numeric' }))
